"""Tables of metric VALUES (not only differences) for Study 2, from results/bon_v2/<set>.json.

    python scripts/15_tables_v2.py                 # -> results/bon_v2/tables.md
    python scripts/15_tables_v2.py --sets S500 R2000 RFULL

For each set: the value of every metric at N = 16 for every verifier, next to the two N = 1
references (sample 0, registered; the average single draw, amendment 3); then FID and CLIP at
every N. Values only; the differences with their CIs are in report_<set>.md. Every number is
read from the JSON, nothing is retyped.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))
from eotts.provenance import REPO_ROOT

ap = argparse.ArgumentParser()
ap.add_argument("--sets", nargs="+", default=["S500", "R2000", "RFULL"])
ap.add_argument("--dir", default=os.path.join(REPO_ROOT, "results", "bon_v2"))
args = ap.parse_args()

NAMES = {"v1": "V1 RemoteCLIP", "v2": "V2 GeoRSCLIP", "v1+v2": "V1+V2", "v3": "V3 VLM (secondary)",
         "v1+v3": "V1+V3 (secondary)"}
TITLE = {"S500": "S500 (500 Git-Spatial tiles, held-out region)", "R2000": "R2000 (2,000 Git-Rand tiles)",
         "RFULL": "RFULL (all 14,932 Git-Rand tiles)"}
COLS = ["CLIP ↑", "LPIPS ↓", "SSIM ↑", "FID ↓", "KID-Inception ×10³ ↓", "KID-DINOv2 ×10³ ↓"]


def row(label, v):
    return (f"| {label} | {v['clip_cos']:.4f} | {v['lpips']:.4f} | {v['ssim']:.4f} | {v['fid']:.2f} | "
            f"{v['kid_inception'] * 1e3:.2f} | {v['kid_dino'] * 1e3:.1f} |")


def values(cell):
    return {"clip_cos": cell["clip_cos"]["mean"], "lpips": cell["lpips"]["mean"], "ssim": cell["ssim"]["mean"],
            "fid": cell["fid"]["full_sample"], "kid_inception": cell["kid_inception"]["mmd2_full_sample"],
            "kid_dino": cell["kid_dino"]["mmd2_full_sample"]}


L = ["# Study 2: metric values", "",
     "Generated by `scripts/15_tables_v2.py` from `results/bon_v2/<set>.json`. Values, not differences: "
     "the differences with 95 % CIs and significance are in `report_<set>.md` and "
     "[docs/bon_v2_results.md](../../docs/bon_v2_results.md). FID on fewer than 14,932 images is biased "
     "upward: compare FID only within a set.", ""]
for s in args.sets:
    p = os.path.join(args.dir, f"{s}.json")
    if not os.path.exists(p):
        print(f"[tables] {s}: no {p}, skipped")
        continue
    r = json.load(open(p, encoding="utf-8"))
    rules = list(r["rules"])
    k0 = values(r["rules"]["v1"]["1"])
    L += [f"## {TITLE.get(s, s)}", "", f"Values at N = 16 (best of 16 samples per tile), and the two N = 1 references.", "",
          "| Selection | " + " | ".join(COLS) + " |", "| --- |" + " --- |" * len(COLS),
          row("N = 1: sample 0 (registered reference)", k0)]
    if "mean_draw_fid_full_sample" in r:
        c16 = r["rules"]["v1"]["16"]
        md = {m: c16[m]["mean"] - c16[m]["diff_vs_mean_draw"]["estimate"] for m in ("clip_cos", "lpips", "ssim")}
        md["fid"] = r["mean_draw_fid_full_sample"]
        md.update({n: r["mean_draw_kid_full_sample"][n] for n in ("kid_inception", "kid_dino")})
        L.append(row("N = 1: average single draw (amendment 3)", md))
    for rule in rules:
        L.append(row(f"N = 16: {NAMES.get(rule, rule)}", values(r["rules"][rule]["16"])))
    if "oracle" in r:
        o = r["oracle"]
        L.append(f"| N = 16: oracle (upper bound, picks by the evaluator itself) | {o['clip_cos']['16']:.4f} | "
                 f"{o['lpips']['16']:.4f} | {o['ssim']['16']:.4f} | – | – | – |")
    ns = [str(n) for n in r["n_values"]]
    for metric, label, fmt in (("fid", "FID ↓", "{:.2f}"), ("clip_cos", "CLIP score ↑", "{:.4f}"),
                               ("kid_dino", "KID-DINOv2 ×10³ ↓", None)):
        L += ["", f"{label} at every N ({s}):", "", "| Verifier | " + " | ".join(f"N = {n}" for n in ns) + " |",
              "| --- |" + " --- |" * len(ns)]
        for rule in rules:
            vals = [values(r["rules"][rule][n])[metric] for n in ns]
            txt = [f"{v * 1e3:.1f}" for v in vals] if metric == "kid_dino" else [fmt.format(v) for v in vals]
            L.append(f"| {NAMES.get(rule, rule)} | " + " | ".join(txt) + " |")
        if metric == "fid" and "per_draw_fid_full_sample" in r:
            pd = r["per_draw_fid_full_sample"]
            L += ["", f"FID of the 16 single draws (sample k of every tile): "
                      + ", ".join(f"{x:.2f}" for x in pd) + f"; mean {sum(pd) / len(pd):.2f}."]
    L.append("")

out = os.path.join(args.dir, "tables.md")
open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
print(f"[tables] -> {out}")
