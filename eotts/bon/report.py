"""Readable Markdown report of the Best-of-N analysis."""
from __future__ import annotations

from eotts.bon.select import RULES

RULE_NAME = {"v1": "V1 RemoteCLIP-B/32", "v2": "V2 GeoRSCLIP-L/14", "v1+v2": "V1+V2 rank average",
             "v3": "V3 VLM P(yes) (secondary)", "v1+v3": "V1+V3 rank average (secondary)"}


def _ci(d, scale=1.0, digits=4):
    f = f"{{:+.{digits}f}}"
    return f"{f.format(d['estimate'] * scale)} [{f.format(d['ci_low'] * scale)}, {f.format(d['ci_high'] * scale)}]"


def write_report(per_set, ends, anchors, path):
    L = ["# Best-of-N results", "",
         "Generated by `scripts/07_analyze_bon.py` from cached scores. Protocol: "
         "[docs/experiment_protocol.md](../../docs/experiment_protocol.md). Differences are against "
         "N = 1 on the same tiles, with 95 % paired bootstrap CIs. KID differences are ×10³ "
         "(full-sample unbiased MMD²).", ""]
    if ends:
        L += ["## Primary endpoints", "",
              "CLIP score (E1), N = 16 vs N = 1, Holm-corrected over verifier × set:", "",
              "| Set / rule | Δ CLIP [95 % CI] | p (bootstrap) | p (Holm) | Significant |",
              "| --- | --- | --- | --- | --- |"]
        for k, v in ends["primary_clip_n16_vs_n1"].items():
            L.append(f"| {k} | {_ci(v)} | {v['p']:.4f} | {v['p_holm']:.4f} | {'yes' if v['reject'] else 'no'} |")
        L += ["", "Guard: KID-DINOv2 (E5) at N = 16 non-inferior to N = 1 (upper CI < 10 % of KID at N = 1):", "",
              "| Set / rule | Δ KID-DINOv2 ×10³ [95 % CI] | Margin ×10³ | Non-inferior |",
              "| --- | --- | --- | --- |"]
        for k, g in ends["guard_kid_dino_n16_vs_n1"].items():
            if g["non_inferior"] is None:
                L.append(f"| {k} | {_ci(g['diff'], 1e3, 3)} | undefined (KID at N = 1 is {g['kid_dino_n1'] * 1e3:.3f}) | undefined |")
            else:
                L.append(f"| {k} | {_ci(g['diff'], 1e3, 3)} | {g['margin'] * 1e3:.3f} | {'yes' if g['non_inferior'] else 'no'} |")
        L.append("")

    for s, r in per_set.items():
        L += [f"## {s} ({r['tiles']} tiles × {r['samples_per_tile']} samples)", "",
              "| Rule | N | Δ CLIP | Δ LPIPS (lower better) | Δ SSIM | Δ KID-Inception ×10³ | Δ KID-DINOv2 ×10³ |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
        for rule in RULES:
            for n, c in r["rules"][rule].items():
                if n == "1":
                    continue
                L.append(f"| {RULE_NAME[rule]} | {n} | {_ci(c['clip_cos']['diff_vs_n1'])} | "
                         f"{_ci(c['lpips']['diff_vs_n1'])} | {_ci(c['ssim']['diff_vs_n1'])} | "
                         f"{_ci(c['kid_inception']['diff_vs_n1'], 1e3, 3)} | {_ci(c['kid_dino']['diff_vs_n1'], 1e3, 3)} |")
        n1 = r["rules"]["v1"]["1"]
        L += ["", f"N = 1 (no selection): CLIP {n1['clip_cos']['mean']:.4f}, LPIPS {n1['lpips']['mean']:.4f}, "
                  f"SSIM {n1['ssim']['mean']:.4f}, KID-Inception ×10³ {r['n1_kid_full_sample']['kid_inception'] * 1e3:.3f}, "
                  f"KID-DINOv2 ×10³ {r['n1_kid_full_sample']['kid_dino'] * 1e3:.3f}.", "",
              "Oracle (best of N by the evaluator itself; an upper bound, not a method):", "",
              "| Metric | " + " | ".join(f"N={n}" for n in r["oracle"]["clip_cos"]) + " |",
              "| --- |" + " --- |" * len(r["oracle"]["clip_cos"])]
        for m, vals in r["oracle"].items():
            L.append(f"| {m} | " + " | ".join(f"{v:.4f}" for v in vals.values()) + " |")
        L += ["", "Spearman correlation between verifier and evaluator scores (pooled over all samples; "
                  "mean within tile):", "", "| Verifier ~ evaluator | Pooled | Within tile |", "| --- | --- | --- |"]
        for k, v in r["verifier_evaluator_spearman"].items():
            L.append(f"| {k} | {v['pooled']:.3f} | {v['within_tile_mean']:.3f} |")
        L += ["", "Verifier validity on real tiles (share of other captions ranked above the tile's own; 0.5 = chance):", ""]
        for k, v in r["verifier_validity_gt"].items():
            L.append(f"- {k}: {v['own_caption_rank_pct_mean']:.3f}")
        L.append("")

    if anchors:
        L += ["## Anchors", ""]
        for k, a in anchors.items():
            if k in ("provenance", "stop_rule"):
                continue
            L.append(f"**{k}**: {a.get('label', a.get('a', '') + ' vs ' + a.get('b', ''))}")
            L.append("")
            for m in ("clip_cos", "lpips", "ssim"):
                if m not in a:
                    continue
                x = a[m]
                if "diff" in x:
                    L.append(f"- {m}: {x['mean_a']:.4f} vs {x['mean_b']:.4f}, Δ {_ci(x['diff'])}")
                else:
                    L.append(f"- {m}: {x['mean']:.4f} [{x['ci_low']:.4f}, {x['ci_high']:.4f}], reference "
                             f"{x['reference']}, inside CI: {x['reference_inside_ci']}")
            if "pixels" in a:
                p = a["pixels"]
                L.append(f"- PSNR fp32 vs bf16, same noise: mean {p['psnr_db_mean']:.1f} dB, "
                         f"5th pct. {p['psnr_db_p05']:.1f} dB, min {p['psnr_db_min']:.1f} dB")
            L.append("")
        sr = anchors.get("stop_rule", {})
        L += [f"Stop rule ({sr.get('rule', '')}): **{'TRIGGERED' if sr.get('stop') else 'not triggered'}**", ""]
    open(path, "w", encoding="utf-8").write("\n".join(L) + "\n")


def _verdict_fid(v):
    if not v["reject"]:
        return "no significant change"
    return "significant decrease (better)" if v["estimate"] < 0 else "significant increase (worse)"


def write_report_v2(r, ends, anchors, prefix, path, set_label="RFULL"):
    """Report of protocol v2 (Study 2): one set, primary CLIP + FID, guard, all cells, anchors."""
    title = {"RFULL": "all of Git-Rand", "R2000": "2,000 Git-Rand tiles (R2000)",
             "S500": "500 Git-Spatial tiles (S500)"}.get(set_label, set_label)
    L = [f"# Study 2: Best-of-N with TerraDiT-Ω-B on {title}", "",
         "Generated by `scripts/10_analyze_v2.py` from cached scores. Protocol: "
         "[docs/experiment_protocol_v2.md](../../docs/experiment_protocol_v2.md). Differences are against "
         "N = 1 on the same tiles, with 95 % paired tile-bootstrap CIs. KID is ×10³ (full-sample unbiased MMD²).", "",
         "## Primary endpoints (N = 16 vs N = 1, Holm over 2 metrics × 3 rules)", "",
         *(["FID on fewer than 14,932 images is biased upward: compare it only within this set, not with "
            "the full-split baseline (21.51) or the paper.", ""] if set_label != "RFULL" else []),
         "| Rule | Δ CLIP [95 % CI] | p (Holm) | Δ FID [95 % CI] | p (Holm) | Guard: Δ KID-DINOv2 ×10³ [95 % CI] | Margin ×10³ | Guard | Verdict |",
         "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    P, G = ends["primary_n16_vs_n1"], ends["guard_kid_dino_n16_vs_n1"]
    for rule in RULES:
        c, f, g = P[f"clip_cos/{rule}"], P[f"fid/{rule}"], G[rule]
        guard = "undefined" if g["non_inferior"] is None else ("pass" if g["non_inferior"] else "**fail**")
        margin = "–" if g["margin"] is None else f"{g['margin'] * 1e3:.3f}"
        improvement = (c["reject"] and c["estimate"] > 0 and not (f["reject"] and f["estimate"] > 0)
                       and g["non_inferior"] is True)
        L.append(f"| {RULE_NAME[rule]} | {_ci(c)} | {c['p_holm']:.4f} | {_ci(f, 1.0, 3)} | {f['p_holm']:.4f} | "
                 f"{_ci(g['diff'], 1e3, 3)} | {margin} | {guard} | "
                 f"{'improvement' if improvement else 'not an improvement'}; FID: {_verdict_fid(f)} |")
    n1 = r["rules"]["v1"]["1"]
    L += ["", f"N = 1 (no selection, bf16): CLIP {n1['clip_cos']['mean']:.4f}, LPIPS {n1['lpips']['mean']:.4f}, "
              f"SSIM {n1['ssim']['mean']:.4f}, FID {r['n1_fid_full_sample']:.3f}, "
              f"KID-Inception ×10³ {r['n1_kid_full_sample']['kid_inception'] * 1e3:.3f}, "
              f"KID-DINOv2 ×10³ {r['n1_kid_full_sample']['kid_dino'] * 1e3:.3f}.", "",
          "An improvement needs a significant CLIP gain, no significant FID increase and a passed guard "
          "(protocol v2, Endpoints).", ""]

    def cells(res, title):
        out = [f"## {title}", "",
               "| Rule | N | Δ CLIP | Δ LPIPS (lower better) | Δ SSIM | Δ FID (lower better) | FID | "
               "Δ KID-Inception ×10³ | Δ KID-DINOv2 ×10³ |",
               "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
        for rule in res["rules"]:
            for n, c in res["rules"][rule].items():
                if n == "1":
                    continue
                out.append(f"| {RULE_NAME[rule]} | {n} | {_ci(c['clip_cos']['diff_vs_n1'])} | "
                           f"{_ci(c['lpips']['diff_vs_n1'])} | {_ci(c['ssim']['diff_vs_n1'])} | "
                           f"{_ci(c['fid']['diff_vs_n1'], 1.0, 3)} | {c['fid']['full_sample']:.3f} | "
                           f"{_ci(c['kid_inception']['diff_vs_n1'], 1e3, 3)} | {_ci(c['kid_dino']['diff_vs_n1'], 1e3, 3)} |")
        return out + [""]

    L += cells(r, f"All cells, {set_label} ({r['tiles']} tiles × {r['samples_per_tile']} samples)")
    L += ["Oracle (best of N by the evaluator itself; an upper bound, not a method):", "",
          "| Metric | " + " | ".join(f"N={n}" for n in r["oracle"]["clip_cos"]) + " |",
          "| --- |" + " --- |" * len(r["oracle"]["clip_cos"])]
    for m, vals in r["oracle"].items():
        L.append(f"| {m} | " + " | ".join(f"{v:.4f}" for v in vals.values()) + " |")
    L += ["", "Spearman correlation between verifier and evaluator scores:", "",
          "| Verifier ~ evaluator | Pooled | Within tile |", "| --- | --- | --- |"]
    for k, v in r["verifier_evaluator_spearman"].items():
        L.append(f"| {k} | {v['pooled']:.3f} | {v['within_tile_mean']:.3f} |")
    L += ["", "Verifier validity on real tiles (share of other captions ranked above the tile's own; 0.5 = chance):", ""]
    for k, v in r["verifier_validity_gt"].items():
        L.append(f"- {k}: {v['own_caption_rank_pct_mean']:.3f}")
    L.append("")
    if prefix:
        L += cells(prefix, f"Secondary: R2000 prefix (first {prefix['tiles']} tiles, the Study 1 R2000 tiles). "
                           "FID here is biased by the small n: compare only within this table")
    if anchors:
        L += ["## Anchors", ""]
        for k, a in anchors.items():
            if k in ("provenance", "stop_rule"):
                continue
            if k.startswith("1_"):
                L.append(f"**{k}**: {a['label']}")
                L.append("")
                for m, v in a["ours"].items():
                    ref = a["paper_ablation"].get(m)
                    L.append(f"- {m}: {v:.4f}" + (f" (paper ablation: {ref})" if ref is not None else ""))
                L.append("")
                continue
            L.append(f"**{k}**: {a.get('a', '')} vs {a.get('b', '')}")
            L.append("")
            for m in ("clip_cos", "lpips", "ssim"):
                if m in a:
                    x = a[m]
                    L.append(f"- {m}: {x['mean_a']:.4f} vs {x['mean_b']:.4f}, Δ {_ci(x['diff'])}")
            if "fid" in a:
                L.append(f"- FID: {a['fid']['a']:.3f} vs {a['fid']['b']:.3f}, Δ {_ci(a['fid']['diff'], 1.0, 3)}")
            for name in ("kid_inception", "kid_dino"):
                if name in a:
                    L.append(f"- {name} ×10³ (subset KID): {a[name]['a']['kid'] * 1e3:.3f} vs {a[name]['b']['kid'] * 1e3:.3f}")
            if "pixels" in a:
                p = a["pixels"]
                L.append(f"- PSNR fp32 vs bf16, same noise: mean {p['psnr_db_mean']:.1f} dB, "
                         f"5th pct. {p['psnr_db_p05']:.1f} dB, min {p['psnr_db_min']:.1f} dB")
            L.append("")
        sr = anchors.get("stop_rule", {})
        L += [f"Stop rule ({sr.get('rule', '')}): **{'TRIGGERED' if sr.get('stop') else 'not triggered'}**", ""]
        for fl in sr.get("flags", []):
            L.append(f"- {fl}")
    open(path, "w", encoding="utf-8").write("\n".join(L) + "\n")
